from __future__ import annotations
import argparse
from pathlib import Path
import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parent
FEATURES = [
    "Type", "Air temperature [K]", "Process temperature [K]",
    "Rotational speed [rpm]", "Torque [Nm]", "Tool wear [min]",
]


def main() -> None:
    parser = argparse.ArgumentParser(description="UCI AI4I 設備故障風險示範")
    parser.add_argument("--demo", choices=["high", "low"], help="使用訓練程式儲存的高/低分數範例")
    parser.add_argument("--type", choices=["L", "M", "H"], default="L")
    parser.add_argument("--air-temp", type=float, default=298.1)
    parser.add_argument("--process-temp", type=float, default=308.5)
    parser.add_argument("--speed", type=float, default=1400)
    parser.add_argument("--torque", type=float, default=42)
    parser.add_argument("--wear", type=float, default=180)
    parser.add_argument("--threshold", type=float, default=0.5, help="示範用分類門檻，預設 0.5")
    args = parser.parse_args()
    if not 0 <= args.threshold <= 1:
        parser.error("threshold 必須介於 0 和 1")

    model_path = ROOT / "artifacts_maxFeature4_leaf2" / "model.joblib"

    if args.demo:
        demo_path = ROOT / "artifacts_maxFeature4_leaf5" / "demo_examples.csv"
        samples = pd.read_csv(demo_path)
        row_index = samples["predicted_probability"].idxmax() if args.demo == "high" else samples["predicted_probability"].idxmin()
        X = samples.loc[[row_index], FEATURES]
        print(f"範例：{args.demo}，資料原始標籤：{int(samples.loc[row_index, 'observed_label'])}")
    else:
        X = pd.DataFrame([{
            "Type": args.type,
            "Air temperature [K]": args.air_temp,
            "Process temperature [K]": args.process_temp,
            "Rotational speed [rpm]": args.speed,
            "Torque [Nm]": args.torque,
            "Tool wear [min]": args.wear,
        }])

    model = joblib.load(model_path)  # Load only models generated by yourself / trusted sources.
    score = float(model.predict_proba(X)[0, 1])
    print("\n輸入的設備條件：")
    print(X.to_string(index=False))
    print(f"\n模型故障風險分數：{score:.1%}")
    print(f"門檻 {args.threshold:.0%} → {'故障風險警示' if score >= args.threshold else '未觸發警示'}")


if __name__ == "__main__":
    main()
